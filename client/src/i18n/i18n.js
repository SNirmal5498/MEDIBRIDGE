export function getCategoryTranslation(langCode, category) {
  if (!category) return "";
  if (langCode === "en") return category;

  const cleanCategory = String(category).trim().replace(/\s+/g, " ");

  // 1. Exact match
  if (CATEGORY_TRANSLATIONS[cleanCategory]?.[langCode]) {
    return CATEGORY_TRANSLATIONS[cleanCategory][langCode];
  }

  // 2. Case-insensitive / normalized lookup
  const normKey = cleanCategory.toLowerCase();
  const foundKey = Object.keys(CATEGORY_TRANSLATIONS).find(
    (k) =>
      k.toLowerCase() === normKey ||
      k.toLowerCase().replace(/&/g, "and") === normKey.replace(/&/g, "and")
  );
  if (foundKey && CATEGORY_TRANSLATIONS[foundKey]?.[langCode]) {
    return CATEGORY_TRANSLATIONS[foundKey][langCode];
  }

  // 3. Composite splitting e.g. "First Aid & Antiseptics" or "Cold / Cough"
  const splitDelimiter = cleanCategory.includes("&") ? "&" : cleanCategory.includes("/") ? "/" : null;
  if (splitDelimiter) {
    const parts = cleanCategory.split(splitDelimiter).map((p) => p.trim());
    const translatedParts = parts.map((part) => getCategoryTranslation(langCode, part));
    const joiner = splitDelimiter === "&" ? " & " : " / ";
    return translatedParts.join(joiner);
  }

  return cleanCategory;
}

