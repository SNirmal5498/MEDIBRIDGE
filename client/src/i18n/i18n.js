export function getCategoryTranslation(langCode, category) {
  if (!category) return "";
  if (langCode === "en") return category;
  
  // Exact match
  if (CATEGORY_TRANSLATIONS[category]?.[langCode]) {
    return CATEGORY_TRANSLATIONS[category][langCode];
  }

  // Case-insensitive / partial search
  const foundKey = Object.keys(CATEGORY_TRANSLATIONS).find(
    (k) => k.toLowerCase() === category.toLowerCase()
  );
  if (foundKey && CATEGORY_TRANSLATIONS[foundKey]?.[langCode]) {
    return CATEGORY_TRANSLATIONS[foundKey][langCode];
  }

  return category;
}

